"""Write tests/fixtures/nomogram_parity.json: inputs and expected outputs of ite_core.nomogram.

The R port (r/iteviz) and the pytest suite both check this one file, so the two implementations cannot drift.
Regenerate after any intentional change to nomogram.py (and bump nomogram.SPEC_VERSION):

    .venv/bin/python scripts/make_parity_fixture.py

All values are synthetic (a grid of scores), never resident data.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ite_core import nomogram  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "nomogram_parity.json"

# Probabilities on and either side of every tier cutoff and prob_label boundary. Tier and label are checked
# directly from these, so a last-digit difference in exp() between Python and R can never flip a boundary case.
EDGE_PROBS = [0.0, 0.0499999, 0.05, 0.0500001, 0.4999999, 0.5, 0.5000001, 0.8999999, 0.9, 0.9000001]
EDGE_PROBS += [0.9499999, 0.95, 0.9500001, 0.998, 1.0, None]


def _num(x):
    """JSON-safe number: NaN/None -> null, numpy scalars -> Python floats."""
    if x is None:
        return None
    x = float(x)
    return None if math.isnan(x) else x


def _str(x):
    return None if x is None or (isinstance(x, float) and math.isnan(x)) else str(x)


def build_fixture() -> dict:
    lo, hi = nomogram.DEFAULT_CUTOFFS

    pairs = [(pct, pgy) for pgy in (1, 2, 3) for pct in range(20, 101)]
    # Fractional scores, PGY clamping (0, 4, -1), truncation (2.7 -> 2), PGY given as text, and missing values.
    pairs += [(64.5, 2), (71.25, 3), (65, 0), (65, 4), (65, -1), (65, 2.7), (65, "3"), (None, 2), (65, None)]
    point_cases = []
    for pct, pgy in pairs:
        p = nomogram.pass_prob(pct, pgy)
        point_cases.append(
            dict(pct=pct, pgy=pgy, prob=_num(p), tier=nomogram.risk_tier(p), label=nomogram.prob_label(p))
        )

    probs = EDGE_PROBS + [round(k / 100, 2) for k in range(5, 96)]
    prob_cases = [dict(prob=p, tier=nomogram.risk_tier(p), label=nomogram.prob_label(p)) for p in probs]

    custom_cutoff_cases = [
        dict(prob=p, cutoffs=list(c), tier=nomogram.risk_tier(p, c))
        for c in [(0.5, 0.75), (0.4, 0.8)]
        for p in (0.39, 0.4, 0.49, 0.5, 0.74, 0.75, 0.79, 0.8, 0.95)
    ]

    pct_for_prob_cases = [
        dict(prob=p, pgy=pgy, pct=nomogram.pct_for_prob(p, pgy))
        for pgy in (1, 2, 3)
        for p in (0.05, 0.25, 0.5, 0.75, 0.9, 0.95)
    ]

    tiers = [None, "Low", "Intermediate", "High"]
    tier_change_cases = [dict(prev=a, cur=b, out=nomogram.tier_change(a, b)) for a in tiers for b in tiers]

    trajectory_cases = []
    for scores in [{1: 65, 2: 65, 3: 65}, {1: 55, 2: 62}, {1: 48, 2: 60, 3: 72}, {1: 60, 2: None, 3: 66}, {3: 58}]:
        t = nomogram.trajectory(scores)
        rows = [
            dict(
                pgy=int(r.PGY),
                pct_correct=_num(r.Pct_Correct),
                pass_prob=_num(r.Pass_Prob),
                risk_tier=_str(r.Risk_Tier),
                pct_needed_low=_num(r.Pct_Needed_Low),
                delta_pct=_num(r.Delta_Pct),
                tier_change=_str(r.Tier_Change),
            )
            for r in t.itertuples()
        ]
        trajectory_cases.append(dict(scores={str(k): v for k, v in scores.items()}, rows=rows))

    c = nomogram.curves(step=5, lo=20, hi=100)
    curves_case = dict(
        step=5,
        lo=20,
        hi=100,
        rows=[
            dict(pgy=int(r.PGY), pct_correct=float(r.Pct_Correct), pass_prob=float(r.Pass_Prob)) for r in c.itertuples()
        ],
        n_rows_step_half_30_95=len(nomogram.curves(step=0.5, lo=30, hi=95)),
    )

    return dict(
        spec_version=nomogram.SPEC_VERSION,
        note="Generated by scripts/make_parity_fixture.py from ite_core/nomogram.py. Do not edit by hand.",
        coefficients={str(k): list(v) for k, v in nomogram.NOMOGRAM.items()},
        cutoffs=[lo, hi],
        tier_label=dict(High="High risk", Intermediate="Intermediate risk", Low="Low risk"),
        point_cases=point_cases,
        prob_cases=prob_cases,
        custom_cutoff_cases=custom_cutoff_cases,
        pct_for_prob_cases=pct_for_prob_cases,
        tier_change_cases=tier_change_cases,
        trajectory_cases=trajectory_cases,
        curves_case=curves_case,
    )


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build_fixture(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[2])}")


if __name__ == "__main__":
    main()
